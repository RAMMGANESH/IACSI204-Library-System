@app.route("/api/loans", methods=["GET"])
def get_loans():
  try:
    conn = get_connection()
    cursor = conn.cursor()
    query = """
            SELECT l.loan_id, b.title, m.name, 
                   TO_CHAR(l.issue_date, 'YYYY-MM-DD'), 
                   TO_CHAR(l.due_date, 'YYYY-MM-DD'), 
                   l.status
            FROM Loans l
            JOIN Books b ON l.book_id = b.book_id
            JOIN Members m ON l.member_id = m.member_id
            ORDER BY l.loan_id DESC
        """
    cursor.execute(query)
    rows = cursor.fetchall()
    loans = [
        {
            "loan_id": r[0],
            "book_title": r[1],
            "member_name": r[2],
            "issue_date": r[3],
            "due_date": r[4],
            "status": r[5],
        }
        for r in rows
    ]
    cursor.close()
    conn.close()
    return jsonify(loans)
  except Exception as e:
    return jsonify({"error": str(e)}), 500


@app.route("/api/books/add", methods=["POST"])
def add_book():
  try:
    data = request.json
    conn = get_connection()
    cursor = conn.cursor()
    copies = int(data["total_copies"])
    cursor.execute(
        """
            INSERT INTO Books (title, author, category, total_copies, available_copies)
            VALUES (:1, :2, :3, :4, :5)
        """,
        (data["title"], data["author"], data["category"], copies, copies),
    )
    conn.commit()
    cursor.close()
    conn.close()
    return jsonify({"message": "Book inserted successfully"}), 201
  except Exception as e:
    return jsonify({"error": str(e)}), 500

@app.route("/api/loans/issue", methods=["POST"])
def issue_book():
  try:
    data = request.json
    book_id = int(data["book_id"])
    member_id = int(data["member_id"])
    due_date = data["due_date"]

    conn = get_connection()
    cursor = conn.cursor()

    cursor.execute(
        "SELECT available_copies FROM Books WHERE book_id = :1", (book_id,)
    )
    stock = cursor.fetchone()
    if not stock or stock[0] <= 0:
      cursor.close()
      conn.close()
      return jsonify({"error": "No copies available in stock"}), 400

    cursor.execute(
        """
            INSERT INTO Loans (book_id, member_id, due_date, status)
            VALUES (:1, :2, TO_DATE(:3, 'YYYY-MM-DD'), 'ACTIVE')
        """,
        (book_id, member_id, due_date),
    )

    cursor.execute(
        """
            UPDATE Books 
            SET available_copies = available_copies - 1 
            WHERE book_id = :1
        """,
        (book_id,),
    )

    conn.commit()
    cursor.close()
    conn.close()
    return jsonify({"message": "Book issued successfully"}), 201
  except Exception as e:
    return jsonify({"error": str(e)}), 500


