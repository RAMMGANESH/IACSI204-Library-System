@app.route("/api/books", methods=["GET"])
def get_books():
  try:
    conn = get_connection()
    cursor = conn.cursor()
    cursor.execute(
        "SELECT book_id, title, author, category, total_copies,"
        " available_copies FROM Books ORDER BY book_id DESC"
    )
    rows = cursor.fetchall()
    books = [
        {
            "book_id": r[0],
            "title": r[1],
            "author": r[2],
            "category": r[3],
            "total_copies": r[4],
            "available_copies": r[5],
        }
        for r in rows
    ]
    cursor.close()
    conn.close()
    return jsonify(books)
  except Exception as e:
    return jsonify({"error": str(e)}), 500


